def main() -> None:
    """写入白名单并保存 manifest。"""
    manifest = json.loads(_MANIFEST.read_text(encoding="utf-8"))
    for code, items in _WHITELIST.items():
        record = manifest["companies"].get(code)
        if record is None:
            print(f"  ✗ 未找到公司 {code}, 跳过")
            continue
        record["known_real_diffs"] = [
            {"rule_id": rule_id, "reason": reason} for rule_id, reason in items
        ]
    _MANIFEST.write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    print(f"manifest 白名单已更新: {_MANIFEST}")


if __name__ == "__main__":
    main()
